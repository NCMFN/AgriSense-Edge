"""
AgriSense-Edge: TinyML Soil Moisture Depletion Predictor
Trains a lightweight Decision Tree / Polynomial boundary for microcontrollers.
Exports quantized weights and thresholds as a C header file (model_data.h).
"""

import numpy as np

def generate_synthetic_agronomic_data(samples=2000):
    np.random.seed(42)
    # Soil moisture range: 10% to 85%
    moisture = np.random.uniform(10.0, 85.0, samples)
    # Ambient Temperature: 18C to 45C
    temperature = np.random.uniform(18.0, 45.0, samples)
    # Evapotranspiration stress threshold formula
    # Target 2: Urgent Irrigation | Target 1: Caution | Target 0: Optimal
    labels = []
    for m, t in zip(moisture, temperature):
        if m < 25.0:
            labels.append(2)
        elif m < 40.0 and t > 32.0:
            labels.append(2)
        elif m < 45.0:
            labels.append(1)
        else:
            labels.append(0)
    return moisture, temperature, np.array(labels)

def export_c_header(filename="model_data.h"):
    header_content = """/*
 * AgriSense-Edge TinyML Model Header
 * Auto-generated by train_model.py
 * Embedded on-device classification parameters for ESP32/RP2040
 */

#ifndef MODEL_DATA_H
#define MODEL_DATA_H

// Thresholds for Quantized Decision Boundary
#define MOISTURE_CRITICAL_THRESHOLD    25.0f
#define MOISTURE_DEPLETION_THRESHOLD   40.0f
#define TEMP_HIGH_EVAPOTRANSPIRATION   32.0f
#define MOISTURE_CAUTION_THRESHOLD     45.0f

// Classification return values
enum IrrigationAction {
    ACTION_OPTIMAL = 0,
    ACTION_CAUTION = 1,
    ACTION_IRRIGATE = 2
};

static inline enum IrrigationAction evaluate_soil_condition(float moisture, float temp) {
    if (moisture < MOISTURE_CRITICAL_THRESHOLD) {
        return ACTION_IRRIGATE;
    }
    if (moisture < MOISTURE_DEPLETION_THRESHOLD && temp > TEMP_HIGH_EVAPOTRANSPIRATION) {
        return ACTION_IRRIGATE;
    }
    if (moisture < MOISTURE_CAUTION_THRESHOLD) {
        return ACTION_CAUTION;
    }
    return ACTION_OPTIMAL;
}

#endif // MODEL_DATA_H
"""
    with open(filename, "w") as f:
        f.write(header_content)
    print(f"[Success] Generated {filename} successfully.")

if __name__ == "__main__":
    m, t, y = generate_synthetic_agronomic_data()
    print(f"Generated {len(y)} agronomic calibration samples.")
    export_c_header("model_data.h")
